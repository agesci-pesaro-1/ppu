// Group's initial data: branches (branche), units (unita) and tag types
// (tipi_tag), read from a JSON configuration file (example:
// config/gruppo.esempio.json) and turned into SQL.
//
// Usage: node scripts/group-seed.ts [file]   (prints the SQL to stdout)
//
// The SQL can be applied again: it adds new entries and leaves existing ones
// untouched (ON CONFLICT DO NOTHING). Apply it before seed/base, which inserts
// the progression catalogue only for the configured branches.
//
// The configuration keys mirror the (Italian) table names of the schema.

import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

export interface GroupConfig {
  branche: { id: string; nome: string }[];
  unita: { id: string; nome: string; branca: string; attiva?: boolean }[];
  tipi_tag: { id: string; nome: string; esclusivo?: boolean }[];
}

export const EXAMPLE_CONFIG = fileURLToPath(
  new URL('../config/gruppo.esempio.json', import.meta.url),
);

const ID = /^[a-z][a-z0-9_]*$/;

export function readGroupConfig(file: string = EXAMPLE_CONFIG): GroupConfig {
  const config = JSON.parse(readFileSync(file, 'utf8')) as GroupConfig;
  validateGroupConfig(config);
  return config;
}

export function validateGroupConfig(config: GroupConfig): void {
  const errors: string[] = [];
  for (const section of ['branche', 'unita', 'tipi_tag'] as const) {
    const entries = config[section];
    if (!Array.isArray(entries)) {
      errors.push(`missing list "${section}"`);
      continue;
    }
    const seen = new Set<string>();
    for (const e of entries) {
      if (typeof e.id !== 'string' || !ID.test(e.id))
        errors.push(`${section}: invalid id "${e.id}"`);
      if (typeof e.nome !== 'string' || !e.nome.trim())
        errors.push(`${section}: "${e.id}" has no name`);
      if (seen.has(e.id)) errors.push(`${section}: duplicate id "${e.id}"`);
      seen.add(e.id);
    }
  }
  if (errors.length === 0) {
    const branches = new Set(config.branche.map((b) => b.id));
    for (const u of config.unita) {
      if (!branches.has(u.branca))
        errors.push(`unita: "${u.id}" uses unknown branch "${u.branca}"`);
    }
    // tag.tipo_id defaults to 'varie': that tag type must exist.
    if (!config.tipi_tag.some((t) => t.id === 'varie'))
      errors.push('tipi_tag: missing type "varie"');
  }
  if (errors.length > 0) throw new Error(`Invalid group configuration:\n- ${errors.join('\n- ')}`);
}

const sql = (v: string | number): string =>
  typeof v === 'number' ? String(v) : `'${v.replaceAll("'", "''")}'`;

function insertBlock(table: string, columns: string[], rows: (string | number)[][]): string {
  if (rows.length === 0) return '';
  const values = rows.map((r) => `  (${r.map(sql).join(', ')})`).join(',\n');
  return `INSERT INTO ${table} (${columns.join(', ')}) VALUES\n${values}\nON CONFLICT (id) DO NOTHING;\n`;
}

export function groupSeedSql(config: GroupConfig): string {
  validateGroupConfig(config);
  return [
    "-- Group's initial data, generated by scripts/group-seed.ts.",
    '',
    insertBlock(
      'branche',
      ['id', 'nome', 'ordine'],
      config.branche.map((b, i) => [b.id, b.nome, i + 1]),
    ),
    insertBlock(
      'unita',
      ['id', 'nome', 'branca_id', 'attiva', 'ordine'],
      config.unita.map((u, i) => [u.id, u.nome, u.branca, u.attiva === false ? 0 : 1, i + 1]),
    ),
    insertBlock(
      'tipi_tag',
      ['id', 'nome', 'esclusivo_predefinito', 'ordine'],
      config.tipi_tag.map((t, i) => [t.id, t.nome, t.esclusivo ? 1 : 0, i + 1]),
    ),
  ].join('\n');
}

if (import.meta.main) {
  try {
    process.stdout.write(groupSeedSql(readGroupConfig(process.argv[2])));
  } catch (error) {
    console.error(error instanceof Error ? error.message : error);
    process.exitCode = 1;
  }
}
